def build_cards():
    """Return the 78 card dicts in deck order."""
    cards = []
    for number, name, archetype, domain, kw, trad, up, rev in MAJOR:
        cards.append(dict(name=name, arcana="Major", suit=None, number=number,
                          archetype=archetype, domain=domain, keywords=kw,
                          traditional=trad, upright=up, reversed=rev))
    for suit, (domain, entries) in SUITS.items():
        for i, (archetype, kw, trad, up, rev) in enumerate(entries, start=1):
            cards.append(dict(name=f"{RANKS[i - 1]} of {suit}", arcana="Minor",
                              suit=suit, number=i, archetype=archetype,
                              domain=domain, keywords=kw, traditional=trad,
                              upright=up, reversed=rev))
    return cards


